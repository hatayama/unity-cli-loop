const (
	testHomebrewArm64SHA256 = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
	testHomebrewAmd64SHA256 = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
)

// TestDispatcherVersionFromReleaseTag verifies dispatcher release tags are stripped and validated.
func TestDispatcherVersionFromReleaseTag(t *testing.T) {
	cases := []struct {
		name    string
		tag     string
		want    string
		wantErr bool
	}{
		{name: "beta tag", tag: "dispatcher-v3.0.0-beta.30", want: "3.0.0-beta.30"},
		{name: "stable tag", tag: "dispatcher-v3.1.0", want: "3.1.0"},
		{name: "missing dispatcher prefix", tag: "v3.0.0", wantErr: true},
		{name: "empty version", tag: "dispatcher-v", wantErr: true},
		{name: "path traversal version", tag: "dispatcher-v../evil", wantErr: true},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := dispatcherVersionFromReleaseTag(tc.tag)
			if tc.wantErr {
				if err == nil {
					t.Fatalf("expected error for tag %q, got version %q", tc.tag, got)
				}
				return
			}
			if err != nil {
				t.Fatalf("dispatcherVersionFromReleaseTag(%q) failed: %v", tc.tag, err)
			}
			if got != tc.want {
				t.Fatalf("dispatcherVersionFromReleaseTag(%q) = %q, want %q", tc.tag, got, tc.want)
			}
		})
	}
}

// TestParseSha256Asset verifies sha256sum-format lines are validated against the expected asset name.
func TestParseSha256Asset(t *testing.T) {
	validHash := testHomebrewArm64SHA256
	validLine := validHash + "  " + homebrewDarwinArm64AssetName + "\n"

	got, err := parseSha256Asset(validLine, homebrewDarwinArm64AssetName)
	if err != nil {
		t.Fatalf("parseSha256Asset failed: %v", err)
	}
	if got != validHash {
		t.Fatalf("hash mismatch: %q", got)
	}

	if _, err := parseSha256Asset("not-a-hash  "+homebrewDarwinArm64AssetName+"\n", homebrewDarwinArm64AssetName); err == nil {
		t.Fatal("expected error for non-hex hash")
	}
	if _, err := parseSha256Asset(validHash+"  wrong-name.tar.gz\n", homebrewDarwinArm64AssetName); err == nil {
		t.Fatal("expected error for filename mismatch")
	}
	if _, err := parseSha256Asset("", homebrewDarwinArm64AssetName); err == nil {
		t.Fatal("expected error for empty input")
	}
}

