func containsFlagName(args []string, name string) bool {
	flag := "-f"
	for index := 0; index < len(args); index++ {
		if args[index] != flag {
			continue
		}
		if index+1 >= len(args) {
			return false
		}
		if strings.HasPrefix(args[index+1], name+"=") {
			return true
		}
	}
	return false
}

func containsFlagValue(args []string, name string, value string) bool {
	expected := name + "=" + value
	for index := 0; index < len(args); index++ {
		if args[index] == "-f" && index+1 < len(args) && args[index+1] == expected {
			return true
		}
		if args[index] == expected {
			return true
		}
	}
	return false
}
